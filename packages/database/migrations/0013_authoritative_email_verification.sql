-- 0013_authoritative_email_verification.sql
-- Authoritative account email verification, verification tokens, and Row Level Security

-- 1. Add email_verified to users with safe default false
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT false;

-- 2. Email verification challenges table
CREATE TABLE IF NOT EXISTS email_verification_tokens (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    sequence_number INTEGER GENERATED BY DEFAULT AS IDENTITY,
    user_id         UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    email           TEXT NOT NULL,
    token_hash      TEXT NOT NULL UNIQUE,
    expires_at      TIMESTAMPTZ NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    consumed_at     TIMESTAMPTZ
);
ALTER TABLE email_verification_tokens ADD COLUMN IF NOT EXISTS sequence_number INTEGER GENERATED BY DEFAULT AS IDENTITY;

-- Indexes for lookups and token consumption
CREATE INDEX IF NOT EXISTS idx_email_verification_user ON email_verification_tokens(user_id);
CREATE INDEX IF NOT EXISTS idx_email_verification_hash ON email_verification_tokens(token_hash) WHERE consumed_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_email_verification_seq ON email_verification_tokens(user_id, sequence_number);

-- 3. Row Level Security for email_verification_tokens
ALTER TABLE email_verification_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE email_verification_tokens FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS email_verification_tokens_policy ON email_verification_tokens;
CREATE POLICY email_verification_tokens_policy ON email_verification_tokens
    FOR ALL USING (is_system_context() OR user_id = get_current_user_id());

-- 4. Grant table privileges to runtime application role
GRANT SELECT, INSERT, UPDATE, DELETE ON email_verification_tokens TO knowledge_app;
