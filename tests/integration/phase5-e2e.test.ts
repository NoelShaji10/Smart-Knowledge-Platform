      expect(deliveredRow?.email_delivery_status).toBe('accepted_by_provider');
      expect(deliveredRow?.email_sent_at).not.toBeNull();
      expect(deliveredRow?.encrypted_token).toBeNull(); // Ciphertext purged

      // 5. Public resolution: GET /api/v1/invitations/:token
