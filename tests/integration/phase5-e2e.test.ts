  describe('Group 4: Email Transport Failure, Retries, and Resend Recovery', () => {
    it('handles retryable transient delivery failures with attempt counters and rethrows for pg-boss', async () => {
      const inviteeEmail = `transient_fail_${Date.now()}@example.com`;
      const createRes = await request(app)
        .post(`/api/v1/workspaces/${workspaceId}/invitations`)
        .set('Authorization', `Bearer ${adminToken}`)
        .send({ email: inviteeEmail, role: 'viewer' });
      const invitationId = createRes.body.invitation.id;

      const invRow = await withSystemContext(async (sysDb) => {
        return sysDb.selectFrom('workspace_invitations').where('id', '=', invitationId).selectAll().executeTakeFirst();
      });
      const encryptedPayload = typeof invRow!.encrypted_token === 'string'
        ? JSON.parse(invRow!.encrypted_token as string)
        : invRow!.encrypted_token;

      // Mock transport throws transient retryable error
      vi.spyOn(mockTransport, 'send').mockRejectedValueOnce(
        new SmtpDeliveryError('Connection timeout', { isRetryable: true, originalCode: '421' })
      );

      // Worker execution should rethrow retryable error
      await expect(
        handleSendInvitationEmail({
          invitationId,
          workspaceId,
          encryptedToken: encryptedPayload,
        })
      ).rejects.toThrow(SmtpDeliveryError);

      // Database assertion: status is 'failed', attempts = 1
      const failedRow = await withSystemContext(async (sysDb) => {
        return sysDb
          .selectFrom('workspace_invitations')
          .where('id', '=', invitationId)
          .select(['email_delivery_status', 'email_delivery_attempts', 'email_failure_reason'])
          .executeTakeFirst();
      });
      expect(failedRow?.email_delivery_status).toBe('failed');
      expect(failedRow?.email_delivery_attempts).toBe(1);
    });

    it('marks permanently_failed on non-retryable 550 SMTP rejection and skips rethrow', async () => {
      const inviteeEmail = `permanent_fail_${Date.now()}@example.com`;
      const createRes = await request(app)
        .post(`/api/v1/workspaces/${workspaceId}/invitations`)
        .set('Authorization', `Bearer ${adminToken}`)
        .send({ email: inviteeEmail, role: 'viewer' });
      const invitationId = createRes.body.invitation.id;

      const invRow = await withSystemContext(async (sysDb) => {
        return sysDb.selectFrom('workspace_invitations').where('id', '=', invitationId).selectAll().executeTakeFirst();
      });
      const encryptedPayload = typeof invRow!.encrypted_token === 'string'
        ? JSON.parse(invRow!.encrypted_token as string)
        : invRow!.encrypted_token;

      // Mock transport throws non-retryable 550
      vi.spyOn(mockTransport, 'send').mockRejectedValueOnce(
        new SmtpDeliveryError('Mailbox does not exist (550)', { isRetryable: false, originalCode: '550' })
      );

      const result = await handleSendInvitationEmail({
        invitationId,
        workspaceId,
        encryptedToken: encryptedPayload,
      });
      expect(result.delivered).toBe(false);

      const dbRow = await withSystemContext(async (sysDb) => {
        return sysDb
          .selectFrom('workspace_invitations')
          .where('id', '=', invitationId)
          .select(['email_delivery_status', 'email_delivery_attempts'])
          .executeTakeFirst();
      });
      expect(dbRow?.email_delivery_status).toBe('permanently_failed');
    });

    it('resends invitation successfully, invalidating superseded delivery jobs', async () => {
      const inviteeEmail = `resend_target_${Date.now()}@example.com`;
      const createRes = await request(app)
        .post(`/api/v1/workspaces/${workspaceId}/invitations`)
        .set('Authorization', `Bearer ${adminToken}`)
        .send({ email: inviteeEmail, role: 'editor' });
      const invitationId = createRes.body.invitation.id;

      const invRow1 = await withSystemContext(async (sysDb) => {
        return sysDb.selectFrom('workspace_invitations').where('id', '=', invitationId).selectAll().executeTakeFirst();
      });
      const stalePayload = typeof invRow1!.encrypted_token === 'string'
        ? JSON.parse(invRow1!.encrypted_token as string)
        : invRow1!.encrypted_token;

      // Admin resends invitation
      const resendRes = await request(app)
        .post(`/api/v1/workspaces/${workspaceId}/invitations/${invitationId}/resend`)
        .set('Authorization', `Bearer ${adminToken}`);
      expect(resendRes.status).toBe(200);
      expect(resendRes.body.rawToken).not.toBe(createRes.body.rawToken);

      // Stale worker running with previous encrypted token detects replacement and halts
      const staleWorkerRes = await handleSendInvitationEmail({
        invitationId,
        workspaceId,
        encryptedToken: stalePayload,
      });
      expect(staleWorkerRes.delivered).toBe(false);
      expect(staleWorkerRes.reason).toBe('INVITATION_REVOKED');

      // Fresh worker delivers the new invitation
      const newInvitationId = resendRes.body.invitation.id;
      const invRow2 = await withSystemContext(async (sysDb) => {
        return sysDb.selectFrom('workspace_invitations').where('id', '=', newInvitationId).selectAll().executeTakeFirst();
      });
      const freshPayload = typeof invRow2!.encrypted_token === 'string'
        ? JSON.parse(invRow2!.encrypted_token as string)
        : invRow2!.encrypted_token;

      const freshWorkerRes = await handleSendInvitationEmail({
        invitationId: newInvitationId,
        workspaceId,
        encryptedToken: freshPayload,
      });
      expect(freshWorkerRes.delivered).toBe(true);
    });
  });

